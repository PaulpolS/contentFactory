const BACKEND_BASE = window.location.port !== '5005' ? 'http://localhost:5005' : '';

/**
 * เติมสมองสำเร็จรูปเข้าคลัง (localStorage + backend) ถ้ายังไม่มี
 * เรียกครั้งเดียวตอนแอปเปิด — ถ้าบอสลบสมอง preset ทิ้งเอง ระบบจะไม่ยัดกลับมาอีก
 */
export async function seedPresetBrains(appendRules?: (content: string) => string) {
  const DISMISSED_KEY = 'preset_brains_seeded';
  let seededIds: string[] = [];
  try { seededIds = JSON.parse(localStorage.getItem(DISMISSED_KEY) || '[]'); } catch {}

  const toSeed = PRESET_BRAINS.filter(p => !seededIds.includes(p.id));
  if (toSeed.length === 0) return;

  // ดึงคลังจาก backend ก่อน เพราะ VerticalVideoSuite ใช้ฝั่ง backend เป็นตัวตั้ง
  let brains: BrainPreset[] = [];
  let backendOk = false;
  try {
    const res = await fetch(`${BACKEND_BASE}/api/get-app-data?key=brains`);
    const data = await res.json();
    backendOk = res.ok;
    if (Array.isArray(data)) brains = data;
  } catch {}

  if (brains.length === 0) {
    try { brains = JSON.parse(localStorage.getItem('system_prompts_brain') || '[]'); } catch {}
  }

  const existingIds = new Set(brains.map(b => b.id));
  const added = toSeed.filter(p => !existingIds.has(p.id));
  const merged = [
    ...brains,
    ...added.map(p => ({ ...p, content: appendRules ? appendRules(p.content) : p.content })),
  ];

  localStorage.setItem('system_prompts_brain', JSON.stringify(merged));
  localStorage.setItem(DISMISSED_KEY, JSON.stringify([...seededIds, ...toSeed.map(p => p.id)]));

  // เขียนกลับ backend เฉพาะตอนที่อ่าน backend สำเร็จ กันเคสเซิร์ฟเวอร์ล่มแล้วไปทับคลังเดิม
  if (!backendOk) return;
  try {
    await fetch(`${BACKEND_BASE}/api/save-app-data`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ key: 'brains', data: merged }),
    });
  } catch (e) {
    console.error('Failed to sync preset brains to backend:', e);
  }
}
